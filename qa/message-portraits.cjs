const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { createRequire } = require('node:module');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ts = createRequire(path.join(root, 'web/package.json'))('typescript');
const source = fs.readFileSync(path.join(root, 'web/src/meeting-presence.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exportsObject = {};
vm.runInNewContext(code, { exports: exportsObject });
const resolve = exportsObject.messageAdvisorKey;
const a = { id: '11111111-1111-1111-1111-111111111111', boardRole: 'Finance', rosterName: 'Fiona' };
const b = { id: '22222222-2222-2222-2222-222222222222', boardRole: 'Operations', rosterName: 'Otto' };
const rows = [a, b];
assert.equal(resolve({ sender: 'advisor', advisorId: b.id, advisorName: 'Finance' }, rows), b.id, 'Stable identity wins over an old name');
assert.equal(resolve({ sender: 'advisor', advisorId: '33333333-3333-3333-3333-333333333333', advisorName: 'Finance' }, rows), null, 'Missing explicit seat never borrows another portrait');
assert.equal(resolve({ sender: 'advisor', advisorId: '00000000-0000-0000-0000-000000000000', advisorName: 'Finance' }, rows), a.id, 'Legacy empty ID resolves unique board role');
assert.equal(resolve({ sender: 'advisor', advisorName: ' fiona ' }, rows), a.id, 'Legacy roster name resolves uniquely');
assert.equal(resolve({ sender: 'advisor', advisorName: 'Finance' }, [a, { ...b, boardRole: 'Finance' }]), null, 'Ambiguous legacy names keep initials');
assert.equal(resolve({ sender: 'advisor', advisorName: 'Unknown' }, rows), null);
assert.equal(resolve({ sender: 'lead', advisorId: a.id, advisorName: 'Finance' }, rows), null);
assert.equal(resolve({ sender: 'secretary', advisorName: 'Finance' }, rows), null);
console.log('PASS message portrait identity: stable IDs, legacy names, missing seats, ambiguity and non-advisor senders');
